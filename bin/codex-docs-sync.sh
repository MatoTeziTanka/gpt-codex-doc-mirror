#!/bin/bash
# codex-docs-sync.sh - Mirror GPT Codex documentation with change tracking
# Purpose: Fetch docs, detect changes, and optionally record in a knowledge graph
# Usage: ./codex-docs-sync.sh [--force]
#
# Configuration via environment variables:
#   DOC_MIRROR_BASE  - Root directory of this tool (defaults to current directory)
#   GRAPH            - Path to a JSONL file for knowledge-graph integration.
#                      If unset, graph logging is skipped entirely.
#
# Example:
#   export DOC_MIRROR_BASE="/opt/doc-mirror"
#   export GRAPH="/opt/graph/nodes.jsonl"   # optional
#   ./bin/codex-docs-sync.sh
#
# Created: 2026-01-28

set -uo pipefail
# Note: -e removed because ((counter++)) returns 1 when counter=0, which exits

# === CONFIGURATION ===
# DOC_MIRROR_BASE: set this to the root of your doc-mirror checkout.
# Defaults to the current working directory if not set.
BASE="${DOC_MIRROR_BASE:-.}"
TOOL_DIR="$BASE"
DATA_DIR="$TOOL_DIR/data/gpt-codex/en"
LOG_DIR="$TOOL_DIR/logs"
# GRAPH: path to a JSONL knowledge-graph file.
# Leave unset to disable graph integration entirely.
GRAPH="${GRAPH:-}"
MANIFEST="$TOOL_DIR/data/gpt-codex/hashes.manifest"
CHANGELOG="$TOOL_DIR/data/gpt-codex/CHANGELOG.md"

BASE_URL="https://developers.openai.com/codex"

# All documentation pages
PAGES=(
    # Core
    "overview.md"
    "quickstart.md"
    "pricing.md"
    "prompting.md"
    "workflows.md"
    "models.md"
    "changelog.md"
    # IDE Extension (subdirectory: ide/)
    "ide/features.md"
    "ide/settings.md"
    "ide/commands.md"
    "ide/slash-commands.md"
    # CLI (subdirectory: cli/)
    "cli/features.md"
    "cli/reference.md"
    "cli/slash-commands.md"
    # Cloud (subdirectory: cloud/)
    "cloud/environments.md"
    "cloud/internet-access.md"
    # Integrations (subdirectory: integrations/)
    "integrations/github.md"
    "integrations/slack.md"
    "integrations/linear.md"
    # Configuration (flat paths)
    "config-advanced.md"
    "config-reference.md"
    "rules.md"
    "mcp.md"
    "skills.md"
    "security.md"
    "windows.md"
    "enterprise.md"
    # Automation & Releases (flat paths)
    "sdk.md"
    "app-server.md"
    "github-action.md"
    "feature-maturity.md"
    "open-source.md"
    # Guides (subdirectory: guides/)
    "guides/agents-md.md"
    "guides/build-ai-native-engineering-team.md"
)

# === FUNCTIONS ===

log() {
    local ts
    ts=$(date -u +%Y-%m-%dT%H:%M:%SZ)
    echo "[$ts] $*" | tee -a "$LOG_DIR/codex-sync.log"
}

get_hash() {
    local file="$1"
    if [[ -f "$file" ]]; then
        sha256sum "$file" | cut -d' ' -f1
    else
        echo "NONE"
    fi
}

graph_change() {
    # Skip if graph integration is not configured
    [[ -z "${GRAPH:-}" ]] && return 0

    local page="$1"
    local change_type="$2"  # new | modified | deleted
    local old_hash="$3"
    local new_hash="$4"

    local ts
    ts=$(date -u +%Y-%m-%dT%H:%M:%S.%6NZ)
    local date_part
    date_part=$(date +%Y-%m-%d)
    # Sanitize page path for node ID (replace / with -)
    local safe_page
    safe_page=$(echo "${page%.md}" | tr '/' '-')
    local node_id="DOC-MIRROR-gpt-codex-${safe_page}-$date_part"

    # Append to graph
    echo "{\"id\": \"$node_id\", \"kind\": \"doc-mirror-change\", \"source\": \"gpt-codex\", \"page\": \"$page\", \"change_type\": \"$change_type\", \"old_hash\": \"$old_hash\", \"new_hash\": \"$new_hash\", \"detected_at\": \"$ts\"}" >> "$GRAPH"

    log "GRAPHED: $node_id ($change_type)"
}

update_changelog() {
    local page="$1"
    local change_type="$2"
    local ts
    ts=$(date -u +%Y-%m-%dT%H:%M:%SZ)

    # Create changelog if doesn't exist
    if [[ ! -f "$CHANGELOG" ]]; then
        cat > "$CHANGELOG" << 'HEADER'
# GPT Codex Documentation Changelog
# Auto-generated by codex-docs-sync.sh

HEADER
    fi

    echo "- [$ts] **$change_type**: $page" >> "$CHANGELOG"
}

fetch_page() {
    local page="$1"
    # Strip .md suffix for the URL (site uses clean URLs without extension)
    local url_path="${page%.md}"
    local url="$BASE_URL/$url_path"
    local dest="$DATA_DIR/$page"
    local tmp_file
    tmp_file=$(mktemp)

    # Ensure destination subdirectory exists
    local dest_dir
    dest_dir=$(dirname "$dest")
    if [[ ! -d "$dest_dir" ]]; then
        mkdir -p "$dest_dir"
    fi

    # Fetch HTML with curl, then extract readable content
    if curl -sfL \
        -H "User-Agent: doc-mirror/1.0 (https://github.com/MatoTeziTanka/claude-code-doc-mirror)" \
        "$url" -o "$tmp_file" 2>/dev/null; then

        # Guard against empty responses
        local file_size
        file_size=$(stat -c%s "$tmp_file" 2>/dev/null || stat -f%z "$tmp_file" 2>/dev/null || echo 0)
        if [[ "$file_size" -lt 64 ]]; then
            log "EMPTY RESPONSE: $page (${file_size} bytes)"
            rm -f "$tmp_file"
            # Preserve old hash if exists
            local old_hash
            old_hash=$(get_hash "$dest")
            if [[ "$old_hash" != "NONE" ]]; then
                echo "$page:$old_hash" >> "$MANIFEST.tmp"
            fi
            return 2
        fi

        # Extract readable content from HTML (site serves HTML, not raw markdown)
        local extract_script
        extract_script="$(dirname "$0")/extract_content.py"
        local extracted_file
        extracted_file=$(mktemp)
        if python3 "$extract_script" "$tmp_file" "$extracted_file" 2>/dev/null; then
            # Swap: use extracted content instead of raw HTML
            rm -f "$tmp_file"
            mv "$extracted_file" "$tmp_file"
        else
            # Extraction failed; keep raw HTML as fallback
            log "EXTRACT WARNING: $page (using raw HTML fallback)"
            rm -f "$extracted_file"
        fi

        # Get hashes
        local old_hash
        old_hash=$(get_hash "$dest")
        local new_hash
        new_hash=$(sha256sum "$tmp_file" | cut -d' ' -f1)

        if [[ "$old_hash" == "NONE" ]]; then
            # New file
            mv "$tmp_file" "$dest"
            log "NEW: $page"
            graph_change "$page" "new" "$old_hash" "$new_hash"
            update_changelog "$page" "NEW"
            echo "$page:$new_hash" >> "$MANIFEST.tmp"
            return 0
        elif [[ "$old_hash" != "$new_hash" ]]; then
            # Modified
            mv "$tmp_file" "$dest"
            log "MODIFIED: $page (${old_hash:0:8}... -> ${new_hash:0:8}...)"
            graph_change "$page" "modified" "$old_hash" "$new_hash"
            update_changelog "$page" "MODIFIED"
            echo "$page:$new_hash" >> "$MANIFEST.tmp"
            return 0
        else
            # Unchanged
            rm "$tmp_file"
            echo "$page:$new_hash" >> "$MANIFEST.tmp"
            return 1
        fi
    else
        log "FETCH FAILED: $page"
        rm -f "$tmp_file"
        # Preserve old hash if fetch fails
        local old_hash
        old_hash=$(get_hash "$dest")
        if [[ "$old_hash" != "NONE" ]]; then
            echo "$page:$old_hash" >> "$MANIFEST.tmp"
        fi
        return 2
    fi
}

# === MAIN ===

log "=== CODEX DOCS SYNC STARTED ==="

# Initialize counters
total=0
new_count=0
modified_count=0
unchanged_count=0
failed_count=0

# Clear temp manifest
rm -f "$MANIFEST.tmp"
touch "$MANIFEST.tmp"

# Process each page
for page in "${PAGES[@]}"; do
    ((total++))

    result=0
    fetch_page "$page" || result=$?

    case $result in
        0)
            if [[ $(get_hash "$DATA_DIR/$page") != "NONE" ]]; then
                # Could be new or modified, check log
                if grep -q "NEW: $page" "$LOG_DIR/codex-sync.log" 2>/dev/null; then
                    ((new_count++))
                else
                    ((modified_count++))
                fi
            fi
            ;;
        1)
            ((unchanged_count++))
            ;;
        2)
            ((failed_count++))
            ;;
    esac
done

# Update manifest
mv "$MANIFEST.tmp" "$MANIFEST"

# Summary
log "=== SYNC COMPLETE ==="
log "Total: $total | New: $new_count | Modified: $modified_count | Unchanged: $unchanged_count | Failed: $failed_count"

# Graph sync event (only if graph integration is configured)
if [[ -n "${GRAPH:-}" ]]; then
    ts=$(date -u +%Y-%m-%dT%H:%M:%S.%6NZ)
    date_part=$(date +%Y-%m-%d)
    echo "{\"id\": \"DOC-SYNC-gpt-codex-$date_part\", \"kind\": \"doc-sync-run\", \"source\": \"gpt-codex\", \"total\": $total, \"new\": $new_count, \"modified\": $modified_count, \"unchanged\": $unchanged_count, \"failed\": $failed_count, \"timestamp\": \"$ts\"}" >> "$GRAPH"
    log "Sync run graphed: DOC-SYNC-gpt-codex-$date_part"
fi

# Exit with appropriate code
if [[ $failed_count -gt 0 ]]; then
    exit 1
elif [[ $((new_count + modified_count)) -gt 0 ]]; then
    exit 0
else
    exit 0
fi
